"""Generate optional Claude cache profiles from the canonical role definitions."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROLES = ("dev-small", "dev-medium", "verifier")


def render(source, role):
    opening, header, body = source.split("---", 2)
    if opening.strip() or f"name: {role}\n" not in header or "experimental:" in header:
        raise ValueError(f"{role}: canonical frontmatter must have one name and no experimental override")
    header = header.replace(f"name: {role}\n", f"name: {role}-long\n", 1)
    lines = header.splitlines()
    for index, line in enumerate(lines):
        if line.startswith("description:"):
            lines[index] += " 5~60분 대기 후 같은 문맥을 재개하는 장기 작업용."
    header = "\n".join(lines).rstrip() + "\nexperimental:\n  cacheTtl: 1h\n"
    return f"---\n# Generated by tools/generate_claude_profiles.py from {role}.md.\n{header.lstrip()}---{body}"


def generate(root=ROOT, write=False):
    agents = Path(root) / "plugins/chef/agents"
    mismatches = []
    for role in ROLES:
        expected = render((agents / f"{role}.md").read_text(encoding="utf-8"), role)
        target = agents / f"{role}-long.md"
        actual = target.read_text(encoding="utf-8") if target.exists() else None
        if actual != expected:
            mismatches.append(str(target))
            if write:
                target.write_text(expected, encoding="utf-8", newline="\n")
    return mismatches


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    mismatches = generate(write=args.write)
    for path in mismatches:
        print(path)
    return 0 if args.write or not mismatches else 1


if __name__ == "__main__":
    raise SystemExit(main())
